/// Every line of `post` that reaches the program, or could: header,
/// operation header, footer, tool change, program end, and the single
/// commands.
fn every_line(post: &PostProcessor) -> Vec<String> {
    let p = &post.program;
    let fs = &post.feed_speed;
    let mut lines: Vec<String> = p
        .header
        .iter()
        .chain(&p.operation_header)
        .chain(&p.footer)
        .chain(&post.tool_change.commands)
        .cloned()
        .collect();
    lines.extend([
        post.stop.program_end_command.clone(),
        fs.spindle_on_cw.clone(),
        fs.spindle_off.clone(),
        fs.spindle_on_dwell.command.clone(),
        post.motion.rapid_command.clone(),
        post.motion.linear_command.clone(),
        post.motion.cw_arc_command.clone(),
        post.motion.ccw_arc_command.clone(),
    ]);
    lines.extend(post.units.mm_command.clone());
    lines.extend(post.units.inch_command.clone());
    lines.extend(post.work_coordinates.select_command.clone());
    if let Some(c) = &post.canned_cycles {
        lines.extend(
            [
                &c.drill_command,
                &c.drill_with_dwell_command,
                &c.peck_drill_command,
                &c.chip_break_drill_command,
            ]
            .into_iter()
            .flatten()
            .cloned(),
        );
        lines.push(c.cancel_command.clone());
    }
    lines
}

/// Design spec, "Post-processor definitions": no tool length offsets.
/// `G43 H` needs a tool table DreamCarve does not write, and the user
/// sets Z zero with each bit instead.
#[test]
fn no_definition_has_g43() {
    for (label, post) in every_version() {
        for line in every_line(post) {
            assert!(
                !words(&line).iter().any(|w| w.starts_with("G43")),
                "{label}: {line}"
            );
        }
    }
}

/// The definitions README, whose per-controller sections cite a source
/// for every line.
const README: &str = include_str!("../../dc-project/src/definitions/README.md");

/// The README section whose `## ` heading names `path` in backticks, up
/// to the next `## ` heading.
fn readme_section(path: &str) -> &'static str {
    let tag = format!("`{path}`");
    let start = README
        .match_indices("\n## ")
        .map(|(i, _)| i + 1)
        .find(|&i| README[i..].lines().next().is_some_and(|h| h.contains(&tag)))
        .unwrap_or_else(|| panic!("no README section for {path}"));
    let rest = &README[start..];
    let end = rest[3..].find("\n## ").map_or(rest.len(), |i| i + 4);
    &rest[..end]
}

/// AGENTS.md, "Reference implementation": controller-facing data is
/// verified against the controller's documentation, with the source cited.
/// Each line of each slice 17 definition appears, in backticks, in the
/// README section for its file, whose table gives the source.
#[test]
fn every_definition_line_is_cited_in_readme() {
    for id in VERIFIED {
        let definition = latest_definition(id).unwrap();
        let section = readme_section(definition.path);
        for line in every_line(definition.post_processor()) {
            assert!(
                section.contains(&format!("`{line}`")),
                "{}: `{line}` is not cited",
                definition.path
            );
        }
    }
}

/// LinuxCNC acts on comments that start with a keyword: `(MSG,`,
/// `(DEBUG,`, `(PRINT,`, `(LOG,`, `(LOGOPEN,file)`, which truncates the
/// file, and `(PROBEOPEN file)` (LinuxCNC G-code overview, "Messages",
/// "Logging", "Probe Logging"). grblHAL acts on `(MSG,`, and with
/// expressions enabled on `(DEBUG,`, `(PRINT,` and `(ABORT,`, which stops
/// the program (`definitions/README.md`, "Comments on grblHAL and GRBL").
/// A project, operation or tool name is the user's text, so no template of
/// the latest version of any definition starts a comment with one (#171).
#[test]
fn user_text_never_starts_a_comment() {
    for definition in latest_definitions().unwrap() {
        let id = definition.path;
        let post = definition.post_processor();
        let p = &post.program;
        let templates = p
            .header
            .iter()
            .chain(&p.operation_header)
            .chain(&p.footer)
            .chain(&post.tool_change.commands);
        for line in templates {
            for (i, _) in line.match_indices(['(', ';']) {
                let after = line[i + 1..].trim_start();
                assert!(!after.starts_with('{'), "{id}: {line}");
            }
        }
    }
}

/// #171: version 2 of grblHAL and GRBL opens the program with fixed text
/// before the project name, and differs from version 1 in nothing else, so
/// a project that upgrades with `export --post <id>` changes one comment.
#[test]
fn grbl_v2_project_comment_opens_with_fixed_text() {
    for (id, first) in [
        ("grblhal", "( Project: {programName} )"),
        ("grbl", "; Project: {programName}"),
    ] {
        let v2 = bundled_definition(id, 2).unwrap().post_processor();
        assert_eq!(
            v2.program.header.first().map(String::as_str),
            Some(first),
            "{id}"
        );
        let mut v1 = bundled_definition(id, 1).unwrap().post_processor().clone();
        v1.program.header[0] = first.to_owned();
        assert_eq!(&v1, v2, "{id}: only the first header line changes");
    }
}

/// #279 (functional capability 29, design addendum A3): version 3 of
/// grblHAL and GRBL is version 2 with `G80` (cancel canned-cycle motion)
/// and then `G40` (cancel cutter compensation) right after `G94`, and
/// nothing else changed. `G80` comes first: on grblHAL with cutter
/// compensation compiled in, `G40` fails while a canned cycle is active
/// (`definitions/README.md`, "Header modal state").
#[test]
fn grbl_v3_header_cancels_modes() {
    for id in ["grblhal", "grbl"] {
        let latest = latest_definition(id).unwrap();
        assert_eq!(latest.version, 3, "{id}");
        let v3 = latest.post_processor();
        let mut v2 = bundled_definition(id, 2).unwrap().post_processor().clone();
        let g94 = v2
            .program
            .header
            .iter()
            .position(|l| l == "G94")
            .unwrap_or_else(|| panic!("{id} v2 has a G94 line"));
        v2.program
            .header
            .splice(g94 + 1..g94 + 1, ["G80".to_owned(), "G40".to_owned()]);
        assert_eq!(&v2, v3, "{id}: v3 is v2 with G80, G40 after G94");
    }
}

/// #279: no version of grblHAL or GRBL changes the tool length offset.
/// Both fold the active offset into the work zero the user sets
/// (`G10 L20`), so a `G49` after the user zeroes Z would move every Z by
/// the offset (`definitions/README.md`, "Header modal state"). `G43` and
/// `G43.2` need a tool table, and `G43.1` sets an offset.
#[test]
fn no_header_cancels_tool_length_offset() {
    let mut checked = 0;
    for definition in bundled_definitions().unwrap() {
        if !["grblhal", "grbl"].contains(&definition.id) {
            continue;
        }
        checked += 1;
        for line in every_line(definition.post_processor()) {
            for word in words(&line) {
                assert!(
                    !(word == "G49" || word.starts_with("G43")),
                    "{}: {line}",
                    definition.path
                );
            }
        }
    }
    assert!(checked >= 6, "grblHAL and GRBL, v1 to v3");
}

/// #286: the user sets Z zero with the bit in the spindle, and on
/// LinuxCNC, Mach3 and UCCNC that zero includes a tool length offset
/// active at the time (`definitions/README.md`, "Tool length offset at
/// touch-off"). A `G49` at program start would cancel it and move every Z
/// by the offset, so version 2 of `id` is version 1 with `G49` taken out
/// of the header and nothing else changed; no line of it can set or
/// cancel an offset (`G43`, `G44`, `G49`), so the offset the user zeroed
/// with stays in force for the whole program.
fn assert_v2_header_has_no_g49(id: &str) {
    let latest = latest_definition(id).unwrap();
    assert_eq!(latest.version, 2, "{id}");
    let v2 = latest.post_processor();
    for line in every_line(v2) {
        for word in words(&line) {
            assert!(
                !["G43", "G44", "G49"].iter().any(|g| word.starts_with(g)),
                "{id} v2: {line}"
            );
        }
    }
    let mut v1 = bundled_definition(id, 1).unwrap().post_processor().clone();
    let modal = v1
        .program
        .header
        .iter_mut()
        .find(|line| words(line).iter().any(|w| w == "G49"))
        .unwrap_or_else(|| panic!("{id} v1 has G49 in its header"));
    *modal = modal.replace(" G49", "");
    assert_eq!(&v1, v2, "{id}: only G49 leaves the header");
}

