//! Checks on the bundled post-processor definitions, over every version
//! of every definition.
//!
//! The definitions themselves live in `dc-project` (`post_processor`,
//! `definitions/`), because loading a project needs them (#106). A project
//! cannot change their fields, only its settings, so the rules a definition
//! must follow are tests here rather than validation. Each check was
//! verified against the controllers' own source and docs; see
//! `dc-project/src/definitions/README.md`, "Verification".

use dc_project::{
    BundledDefinition, PostProcessor, SpindleControl, ToolChangeMode, bundled_definitions,
    is_safe_file_extension, latest_definition, latest_definitions,
};

use crate::emit::{MIN_DECIMAL_PLACES_INCH, MIN_DECIMAL_PLACES_MM};

/// Every bundled definition version with its default settings, and a
/// label for messages: `grblhal v1`.
fn every_version() -> Vec<(String, &'static PostProcessor)> {
    bundled_definitions()
        .unwrap()
        .iter()
        .map(|d: &BundledDefinition| (format!("{} v{}", d.id, d.version), d.post_processor()))
        .collect()
}

#[test]
fn bundled_definitions_validate() {
    let all = bundled_definitions().unwrap();
    assert!(!all.is_empty());
    for d in all {
        assert_eq!(d.path, format!("{}/v{}.json", d.id, d.version));
        assert_eq!(d.post_processor().id, d.id, "{}", d.path);
        assert!(d.post_processor().builtin, "{}", d.path);
    }
    let ids: Vec<&str> = latest_definitions().unwrap().iter().map(|d| d.id).collect();
    assert_eq!(ids, ["grblhal", "grbl"]);
}

#[test]
fn bundled_headers_name_dreamcarve_not_upstream() {
    for (label, post) in every_version() {
        let header = post.program.header.join("\n");
        assert!(
            header.contains("Generated by DreamCarve on {date}"),
            "{label}"
        );
        assert!(!header.contains("PureCutCNC"), "{label}");
    }
}

/// G-code words on a line, outside `( )` and `;` comments, upper-cased.
fn words(line: &str) -> Vec<String> {
    let code = line.split(';').next().unwrap_or("");
    let mut out = String::new();
    let mut depth = 0u32;
    for c in code.chars() {
        match c {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            _ if depth == 0 => out.push(c),
            _ => {}
        }
    }
    out.split_whitespace().map(str::to_uppercase).collect()
}

fn has_word(lines: &[String], word: &str) -> bool {
    lines.iter().any(|l| words(l).iter().any(|w| w == word))
}

#[test]
fn bundled_definitions_select_a_work_coordinate_system() {
    // S5: a controller left in another WCS is corrected.
    for (label, post) in every_version() {
        let wcs = post
            .work_coordinates
            .select_command
            .as_deref()
            .unwrap_or("");
        assert_eq!(wcs, "G54", "{label}");
    }
}

#[test]
fn bundled_headers_set_modal_state() {
    // S5 in spirit: absolute, XY plane, units-per-minute feed (not G93
    // inverse time, which changes what F means), and the units command.
    for (label, post) in every_version() {
        let h = &post.program.header;
        for word in ["G90", "G17", "G94"] {
            assert!(has_word(h, word), "{label} header lacks {word}");
        }
        assert!(h.iter().any(|l| l == "{unitsCommand}"), "{label}");
    }
}

#[test]
fn bundled_footers_stop_the_spindle() {
    // S4: stopped in the footer, not left to M30's side effect.
    for (label, post) in every_version() {
        let off = post.feed_speed.spindle_off.to_uppercase();
        assert!(has_word(&post.program.footer, &off), "{label}");
    }
}

#[test]
fn bundled_footers_make_no_machine_coordinate_moves() {
    // G53 Z0 trips grblHAL soft limits when homed, and on an unhomed
    // machine machine Z0 is wherever Z was at power-on.
    for (label, post) in every_version() {
        assert!(!has_word(&post.program.footer, "G53"), "{label}");
    }
}

#[test]
fn bundled_tool_changes_stop_the_spindle_then_change_once() {
    // #57: grblHAL changes tools with `T<n> M6` after `M5`, and no `M0`
    // (one stop per change). GRBL 1.1 has no M6, so its definition has
    // none and `emit` refuses a second tool; its pause line is kept for
    // comparison with PureCutCNC and never written.
    for (label, post) in every_version() {
        let tc = &post.tool_change;
        assert!(tc.stop_spindle_first, "{label}");
        assert!(!tc.pause_after_change, "{label}");
        let changes: Vec<&String> = tc
            .commands
            .iter()
            .filter(|l| words(l).iter().any(|w| w == "M6"))
            .collect();
        if post.id != "grblhal" {
            assert!(changes.is_empty(), "{label}");
            continue;
        }
        assert_eq!(changes, ["T{toolNumber} M6"], "{label}");
        let off = post.feed_speed.spindle_off.to_uppercase();
        let first_off = tc.commands.iter().position(|l| words(l).contains(&off));
        let change = tc.commands.iter().position(|l| l == changes[0]);
        assert!(
            matches!((first_off, change), (Some(o), Some(c)) if o < c),
            "{label}: spindle must stop before the change"
        );
        assert!(
            !tc.commands
                .iter()
                .any(|l| words(l).iter().any(|w| w == "M0" || w == "M1")),
            "{label}: one stop per tool change"
        );
    }
}

#[test]
fn bundled_templates_use_only_known_placeholders() {
    // The placeholders `emit` fills (docs/specs/phase-1/design.md,
    // "Emission"); anything else would reach the machine as literal text.
    const KNOWN: [&str; 8] = [
        "programName",
        "date",
        "unitsCommand",
        "wcsCommand",
        "operationIndex",
        "operationName",
        "toolNumber",
        "toolName",
    ];
    for (label, post) in every_version() {
        let p = &post.program;
        let lines = p
            .header
            .iter()
            .chain(&p.operation_header)
            .chain(&p.footer)
            .chain(&post.tool_change.commands);
        for line in lines {
            let mut rest = line.as_str();
            while let Some(start) = rest.find('{') {
                let after = &rest[start + 1..];
                let end = after.find('}').unwrap();
                let name = &after[..end];
                assert!(KNOWN.contains(&name), "{label}: unknown {{{name}}}");
                rest = &after[end + 1..];
            }
        }
    }
}

#[test]
fn bundled_text_has_no_real_time_command_bytes() {
    // GRBL and grblHAL act on '!', '~', '?' and every byte above 0x7F
    // the moment they arrive, even inside a comment.
    for d in bundled_definitions().unwrap() {
        let bad: Vec<char> = d
            .source
            .chars()
            .filter(|c| !c.is_ascii() || matches!(c, '!' | '~' | '?'))
            .collect();
        assert!(bad.is_empty(), "{} contains {bad:?}", d.path);
    }
}

#[test]
fn bundled_definitions_dwell_three_seconds_after_spindle_on() {
    // Neither controller waits for spin-up after M3; G4 P is seconds on
    // both (`mc_dwell(float seconds)` in each motion_control.c). The
    // command is the definition's; the 3 s is its default setting.
    for (label, post) in every_version() {
        let dwell = &post.feed_speed.spindle_on_dwell;
        assert!(
            has_word(std::slice::from_ref(&dwell.command), "G4"),
            "{label}"
        );
        assert!(dwell.command.contains("{seconds}"), "{label}");
        assert!(
            (dwell.duration_s - 3.0).abs() < 1e-12,
            "{label}: {} s",
            dwell.duration_s
        );
    }
}

/// #67, #106: an increment of 0 would write `N0` on every line. A project
/// cannot change the increment, so this is checked on the definitions.
#[test]
fn bundled_line_number_increments_are_positive() {
    for (label, post) in every_version() {
        assert!(post.program.line_number_increment > 0, "{label}");
    }
}

/// #106: what `init` and `--post` write is valid: a safe extension, enough
/// decimal places, one program per tool run, and the spindle switched by
/// the program (#34).
#[test]
fn bundled_default_settings_are_valid() {
    for (label, post) in every_version() {
        assert!(is_safe_file_extension(&post.file_extension), "{label}");
        let places = post.number_format.decimal_places;
        assert!(places.mm >= MIN_DECIMAL_PLACES_MM, "{label}");
        assert!(places.inch >= MIN_DECIMAL_PLACES_INCH, "{label}");
        assert_eq!(
            post.tool_change.mode,
            ToolChangeMode::SeparatePrograms,
            "{label}"
        );
        assert_eq!(
            post.feed_speed.spindle_control,
            SpindleControl::Automatic,
            "{label}"
        );
    }
}

/// #34: a project saved before `spindle_control` existed migrates to the
