//! Checks on the bundled post-processor definitions, over every version
//! of every definition.
//!
//! The definitions themselves live in `dc-project` (`post_processor`,
//! `definitions/`), because loading a project needs them (#106). A project
//! cannot change their fields, only its settings, so the rules a definition
//! must follow are tests here rather than validation. Each check was
//! verified against the controllers' own source and docs; see
//! `dc-project/src/definitions/README.md`, "Verification".

use dc_project::{
    BundledDefinition, PostProcessor, SpindleControl, ToolChangeMode, bundled_definition,
    bundled_definitions, is_safe_file_extension, latest_definition, latest_definitions,
};

use crate::emit::{MIN_DECIMAL_PLACES_INCH, MIN_DECIMAL_PLACES_MM};

/// Every bundled definition version with its default settings, and a
/// label for messages: `grblhal v1`.
fn every_version() -> Vec<(String, &'static PostProcessor)> {
    bundled_definitions()
        .unwrap()
        .iter()
        .map(|d: &BundledDefinition| (format!("{} v{}", d.id, d.version), d.post_processor()))
        .collect()
}

/// Design spec, "Post-processor definitions": six controllers, in the
/// order `dreamcarve posts` lists them, each version a valid file under
/// its id.
#[test]
fn six_definitions_validate() {
    let all = bundled_definitions().unwrap();
    assert!(!all.is_empty());
    for d in all {
        assert_eq!(d.path, format!("{}/v{}.json", d.id, d.version));
        assert_eq!(d.post_processor().id, d.id, "{}", d.path);
        assert!(d.post_processor().builtin, "{}", d.path);
    }
    let ids: Vec<&str> = latest_definitions().unwrap().iter().map(|d| d.id).collect();
    assert_eq!(
        ids,
        ["grblhal", "grbl", "linuxcnc", "mach3", "uccnc", "generic"]
    );
}

#[test]
fn bundled_headers_name_dreamcarve_not_upstream() {
    for (label, post) in every_version() {
        let header = post.program.header.join("\n");
        assert!(
            header.contains("Generated by DreamCarve on {date}"),
            "{label}"
        );
        assert!(!header.contains("PureCutCNC"), "{label}");
    }
}

/// G-code words on a line, outside `( )` and `;` comments, upper-cased.
fn words(line: &str) -> Vec<String> {
    let code = line.split(';').next().unwrap_or("");
    let mut out = String::new();
    let mut depth = 0u32;
    for c in code.chars() {
        match c {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            _ if depth == 0 => out.push(c),
            _ => {}
        }
    }
    out.split_whitespace().map(str::to_uppercase).collect()
}

fn has_word(lines: &[String], word: &str) -> bool {
    lines.iter().any(|l| words(l).iter().any(|w| w == word))
}

