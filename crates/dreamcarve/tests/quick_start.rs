//! The quick start chapter, run as written (issue #16;
//! `docs/specs/phase-1/functional.md`, "Documentation deliverables").
//!
//! The steps are read from `docs/book/src/quick-start/first-cut.md` itself,
//! so the chapter and this test cannot drift apart. The chapter marks each
//! step with an HTML comment, which the rendered book does not show, on the
//! line before a fenced block:
//!
//! - `<!-- doc-test: run -->` before a `sh` block: each line is a
//!   `dreamcarve` command, run in order, that must exit 0.
//!   `<!-- doc-test: run, exit N -->` expects exit code `N` instead.
//! - `<!-- doc-test: edit FILE -->` before a block of `"key": value` lines:
//!   the hand edit the chapter asks for. Each key must occur on exactly one
//!   line of `FILE`, or else on the line right after the block's previous
//!   key (the tool's `step_down_mm` follows its `rpm`, #98), and that line's
//!   value is replaced, as a user would in a text editor.
//! - `<!-- doc-test: excerpt FILE -->` before a block: the first lines of
//!   `FILE` as the chapter shows them. The header line carrying the date is
//!   compared up to the date.
//!
//! The chapter's one unmarked setup step, putting a copy of `coaster.svg`
//! in an empty folder, is done here by copying `fixtures/coaster.svg`.
//! Printed output is not compared: the chapter shows it for the reader.

#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::unwrap_used,
    clippy::indexing_slicing,
    reason = "test code reports failure by panicking"
)]

use std::path::{Path, PathBuf};
use std::process::Command;

/// The chapter under test, relative to the repository root.
const CHAPTER: &str = "docs/book/src/quick-start/first-cut.md";

/// The marker that opens every step comment.
const MARKER: &str = "<!-- doc-test:";

/// The header line whose date changes every day.
const DATE_LINE: &str = "Generated by DreamCarve on";

/// One marked step of the chapter.
#[derive(Debug)]
enum Step {
    /// Run `dreamcarve` with `args`; expect exit code `exit`.
    Run {
        args: Vec<String>,
        exit: i32,
        /// 1-based line of the command in the chapter.
        line: usize,
    },
    /// Replace the value of each `(key, value)` in `file`.
    Edit {
        file: String,
        changes: Vec<(String, String)>,
        line: usize,
    },
    /// `file` starts with `lines`.
    Excerpt {
        file: String,
        lines: Vec<String>,
        line: usize,
    },
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// A fresh, empty working directory for test `name`.
fn work_dir(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    if dir.exists() {
        std::fs::remove_dir_all(&dir).expect("old work dir removed");
    }
    std::fs::create_dir_all(&dir).expect("work dir created");
    dir
}

/// The marked steps of `text`, in order. Panics on a marker that is not
/// followed by a fenced block, and on a `sh` block of `dreamcarve` commands
/// that has no marker, so no command in the chapter goes untested.
fn steps(text: &str) -> Vec<Step> {
    let lines: Vec<&str> = text.lines().collect();
    let mut steps = Vec::new();
    let mut pending: Option<(String, usize)> = None;
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i].trim();
        let number = i + 1;
        if let Some(rest) = line.strip_prefix(MARKER) {
            let directive = rest
                .strip_suffix("-->")
                .unwrap_or_else(|| panic!("{CHAPTER}:{number}: marker must end with `-->`"))
                .trim();
            pending = Some((directive.to_owned(), number));
            i += 1;
            continue;
        }
        if let Some(info) = line.strip_prefix("```") {
            let start = i + 1;
            let mut end = start;
            while end < lines.len() && !lines[end].trim().starts_with("```") {
                end += 1;
            }
            assert!(end < lines.len(), "{CHAPTER}:{number}: unclosed code block");
            let body: Vec<&str> = lines[start..end].to_vec();
            match pending.take() {
                Some((directive, at)) => steps.extend(step(&directive, at, start, &body)),
                None => assert!(
                    !(info.trim() == "sh"
                        && body.iter().any(|l| l.trim().starts_with("dreamcarve"))),
                    "{CHAPTER}:{number}: a `sh` block of dreamcarve commands has no `{MARKER}` marker, so the test would not run it"
                ),
            }
            i = end + 1;
            continue;
        }
        if !line.is_empty() {
            assert!(
                pending.is_none(),
                "{CHAPTER}:{number}: a `{MARKER}` marker must be followed by a fenced block"
            );
        }
        i += 1;
    }
    assert!(
        pending.is_none(),
        "{CHAPTER}: marker at the end of the file"
    );
    steps
}

/// The steps one marked block makes. `at` is the marker's line and `first`
/// the 0-based index of the block's first line.
fn step(directive: &str, at: usize, first: usize, body: &[&str]) -> Vec<Step> {
    let (verb, arg) = directive
        .split_once(' ')
        .map_or((directive, ""), |(v, a)| (v, a.trim()));
    match verb.trim_end_matches(',') {
        "run" => {
            let exit = match arg {
                "" => 0,
                _ => arg
                    .strip_prefix("exit ")
                    .and_then(|n| n.trim().parse().ok())
                    .unwrap_or_else(|| panic!("{CHAPTER}:{at}: expected `run, exit N`")),
            };
            body.iter()
                .enumerate()
                .filter(|(_, l)| !l.trim().is_empty() && !l.trim().starts_with('#'))
                .map(|(k, l)| {
                    let line = first + k + 1;
                    assert!(
                        !l.contains(['"', '\'', '$', '|', '>', '<', '&', ';', '`']),
                        "{CHAPTER}:{line}: keep quick-start commands free of shell syntax: {l}"
                    );
                    let mut words = l.split_whitespace();
                    assert_eq!(
                        words.next(),
                        Some("dreamcarve"),
                        "{CHAPTER}:{line}: only dreamcarve commands can be run: {l}"
                    );
                    Step::Run {
                        args: words.map(str::to_owned).collect(),
                        exit,
                        line,
                    }
                })
                .collect()
        }
        "edit" => {
            assert!(!arg.is_empty(), "{CHAPTER}:{at}: `edit` needs a file");
            let changes = body
                .iter()
                .filter(|l| !l.trim().is_empty())
                .map(|l| {
                    let (key, value) = l
                        .trim()
                        .trim_end_matches(',')
                        .split_once(':')
                        .unwrap_or_else(|| {
                            panic!("{CHAPTER}:{at}: not a `\"key\": value` line: {l}")
                        });
                    (key.trim().to_owned(), value.trim().to_owned())
                })
                .collect();
            vec![Step::Edit {
                file: arg.to_owned(),
                changes,
                line: at,
            }]
        }
        "excerpt" => {
            assert!(!arg.is_empty(), "{CHAPTER}:{at}: `excerpt` needs a file");
            vec![Step::Excerpt {
                file: arg.to_owned(),
                lines: body.iter().map(|l| (*l).to_owned()).collect(),
                line: at,
            }]
        }
        other => panic!("{CHAPTER}:{at}: unknown doc-test step `{other}`"),
    }
}

/// Applies a hand edit: each key's line gets the new value, keeping its
/// indentation and any trailing comma. A key on several lines is the one
/// right after the block's previous key, where the chapter shows it.
fn edit(path: &Path, changes: &[(String, String)], at: usize) {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{CHAPTER}:{at}: cannot read {}: {e}", path.display()));
    let mut lines: Vec<String> = text.lines().map(str::to_owned).collect();
    let mut previous: Option<usize> = None;
    for (key, value) in changes {
        let mut found: Vec<usize> = lines
            .iter()
            .enumerate()
            .filter(|(_, l)| l.trim_start().starts_with(&format!("{key}:")))
            .map(|(i, _)| i)
            .collect();
        if found.len() > 1
            && let Some(next) = previous.map(|p| p + 1)
            && found.contains(&next)
        {
            found = vec![next];
        }
        let [index] = found[..] else {
            panic!(
                "{CHAPTER}:{at}: the chapter says to change {key}, which is on {} lines of {}; a reader could not tell which",
                found.len(),
                path.display()
            );
        };
        let old = &lines[index];
        let indent = &old[..old.len() - old.trim_start().len()];
        let comma = if old.trim_end().ends_with(',') {
            ","
        } else {
            ""
        };
        lines[index] = format!("{indent}{key}: {value}{comma}");
        previous = Some(index);
    }
    std::fs::write(path, lines.join("\n") + "\n").expect("edited file written");
}

/// True when `shown` (from the chapter) stands for `actual` (from the
/// file): equal, or both the dated header line.
fn same_line(shown: &str, actual: &str) -> bool {
    shown == actual || (shown.contains(DATE_LINE) && actual.contains(DATE_LINE))
}

/// Every marked step of the quick start chapter, run in order in an empty
/// folder holding `coaster.svg`, does what the chapter says: each command
/// exits with the code the chapter expects, a failed command writes no
/// program, the hand edit applies to exactly the lines it names, and the
/// program excerpt the chapter shows is the start of the written program.
#[test]
fn quick_start_runs_as_written() {
    let path = repo_root().join(CHAPTER);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read the quick start {}: {e}", path.display()));
    let steps = steps(&text);
    assert!(
        steps.iter().any(|s| matches!(s, Step::Run { .. })),
        "{CHAPTER} has no `run` step"
    );
    assert!(
        steps.iter().any(|s| matches!(s, Step::Edit { .. })),
        "{CHAPTER} has no `edit` step: the feeds must be set before export"
    );

    let dir = work_dir("quick_start_runs_as_written");
    std::fs::copy(
        repo_root().join("fixtures/coaster.svg"),
        dir.join("coaster.svg"),
    )
    .expect("coaster.svg copied");

    for step in &steps {
        match step {
            Step::Run { args, exit, line } => {
                let out = Command::new(env!("CARGO_BIN_EXE_dreamcarve"))
                    .current_dir(&dir)
                    // The chapter runs with no user config, whatever the
                    // developer's own `config.toml` says.
                    .env("DREAMCARVE_CONFIG_DIR", dir.join("config"))
                    .args(args)
                    .output()
                    .expect("binary runs");
                assert_eq!(
                    out.status.code(),
                    Some(*exit),
                    "{CHAPTER}:{line}: `dreamcarve {}` exit code\nstdout:\n{}\nstderr:\n{}",
                    args.join(" "),
                    String::from_utf8_lossy(&out.stdout),
                    String::from_utf8_lossy(&out.stderr)
                );
                if *exit != 0 {
                    let programs: Vec<_> = std::fs::read_dir(&dir)
                        .expect("work dir readable")
                        .filter_map(Result::ok)
                        .filter(|e| e.path().extension().is_some_and(|x| x == "nc"))
                        .map(|e| e.path())
                        .collect();
                    assert!(
                        programs.is_empty(),
                        "{CHAPTER}:{line}: `dreamcarve {}` failed but a program exists: {programs:?}",
                        args.join(" ")
                    );
                }
            }
            Step::Edit {
                file,
                changes,
                line,
            } => edit(&dir.join(file), changes, *line),
            Step::Excerpt { file, lines, line } => {
                let actual = std::fs::read_to_string(dir.join(file))
                    .unwrap_or_else(|e| panic!("{CHAPTER}:{line}: cannot read {file}: {e}"));
                let actual: Vec<&str> = actual.lines().collect();
                assert!(
                    lines.len() <= actual.len(),
                    "{CHAPTER}:{line}: excerpt is longer than {file}"
                );
                for (k, (shown, real)) in lines.iter().zip(&actual).enumerate() {
                    assert!(
                        same_line(shown, real),
                        "{CHAPTER}:{line}: excerpt line {} is `{shown}`, but {file} has `{real}`",
                        k + 1
                    );
                }
            }
        }
    }
}
