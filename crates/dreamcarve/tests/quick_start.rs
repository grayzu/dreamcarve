//! The quick start chapters, run as written (issue #16, phase 1's
//! `docs/specs/phase-1/functional.md`, and phase 2's
//! `docs/specs/phase-2/functional.md`, "Documentation deliverables" and
//! acceptance test 18).
//!
//! The steps are read from the chapters themselves, so a chapter and this
//! test cannot drift apart. A chapter marks each step with an HTML comment,
//! which the rendered book does not show, on the line before a fenced block:
//!
//! - `<!-- doc-test: run -->` before a `sh` block: each line is a
//!   `dreamcarve` command, run in order, that must exit 0.
//!   `<!-- doc-test: run, exit N -->` expects exit code `N` instead.
//! - `<!-- doc-test: edit FILE -->` before a block of `"key": value` lines:
//!   the hand edit the chapter asks for. Each key must occur on exactly one
//!   line of `FILE`, or else on the line right after the block's previous
//!   key (the tool's `step_down_mm` follows its `rpm`, #98), and that line's
//!   value is replaced, as a user would in a text editor.
//! - `<!-- doc-test: write FILE -->` before a block: the reader makes `FILE`
//!   with exactly that text.
//! - `<!-- doc-test: paste FILE KEY -->` before a block that starts with
//!   `"KEY":`: the reader selects the `"KEY": [ … ]` (or `{ … }`) block of
//!   `FILE`, from its first line to its closing bracket, and pastes the
//!   chapter's block over it. The pasted lines take the indentation of the
//!   line they replace.
//! - `<!-- doc-test: excerpt FILE -->` before a block: the first lines of
//!   `FILE` as the chapter shows them. The header line carrying the date is
//!   compared up to the date.
//! - `<!-- doc-test: contains FILE -->` before a block: lines that appear,
//!   one after the other, somewhere in `FILE`.
//!
//! Each chapter's unmarked setup step, putting a copy of its drawing in an
//! empty folder, is done here by copying the fixture. Printed output is not
//! compared: the chapter shows it for the reader.

#![allow(
    clippy::expect_used,
    clippy::panic,
    clippy::unwrap_used,
    clippy::indexing_slicing,
    reason = "test code reports failure by panicking"
)]

use std::path::{Path, PathBuf};
use std::process::Command;

use dc_gcode::MachineMove;
use dc_gcode::parse::MotionKind;

/// The phase 1 quick start, relative to the repository root.
const FIRST_CUT: &str = "docs/book/src/quick-start/first-cut.md";

/// The phase 2 quick start, relative to the repository root.
const PLAQUE: &str = "docs/book/src/quick-start/plaque.md";

/// The marker that opens every step comment.
const MARKER: &str = "<!-- doc-test:";

/// The header line whose date changes every day.
const DATE_LINE: &str = "Generated by DreamCarve on";

/// One marked step of a chapter.
#[derive(Debug)]
enum Step {
    /// Run `dreamcarve` with `args`; expect exit code `exit`.
    Run {
        args: Vec<String>,
        exit: i32,
        /// 1-based line of the command in the chapter.
        line: usize,
    },
    /// Replace the value of each `(key, value)` in `file`.
    Edit {
        file: String,
        changes: Vec<(String, String)>,
        line: usize,
    },
    /// Write `lines` as `file`.
    Write {
        file: String,
        lines: Vec<String>,
        line: usize,
    },
    /// Paste `lines` over the `"key":` block of `file`.
    Paste {
        file: String,
        key: String,
        lines: Vec<String>,
        line: usize,
    },
    /// `file` starts with `lines`.
    Excerpt {
        file: String,
        lines: Vec<String>,
        line: usize,
    },
    /// `file` has `lines`, consecutively, somewhere.
    Contains {
        file: String,
        lines: Vec<String>,
        line: usize,
    },
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// A fresh, empty working directory for test `name`.
fn work_dir(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    if dir.exists() {
        std::fs::remove_dir_all(&dir).expect("old work dir removed");
    }
    std::fs::create_dir_all(&dir).expect("work dir created");
    dir
}

/// The marked steps of `text`, the chapter `chapter`, in order. Panics on a
/// marker that is not followed by a fenced block, and on a `sh` block of
/// `dreamcarve` commands that has no marker, so no command in the chapter
/// goes untested.
fn steps(chapter: &str, text: &str) -> Vec<Step> {
    let lines: Vec<&str> = text.lines().collect();
    let mut steps = Vec::new();
    let mut pending: Option<(String, usize)> = None;
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i].trim();
        let number = i + 1;
        if let Some(rest) = line.strip_prefix(MARKER) {
            let directive = rest
                .strip_suffix("-->")
                .unwrap_or_else(|| panic!("{chapter}:{number}: marker must end with `-->`"))
                .trim();
            pending = Some((directive.to_owned(), number));
            i += 1;
            continue;
        }
        if let Some(info) = line.strip_prefix("```") {
            let start = i + 1;
            let mut end = start;
            while end < lines.len() && !lines[end].trim().starts_with("```") {
                end += 1;
            }
            assert!(end < lines.len(), "{chapter}:{number}: unclosed code block");
            let body: Vec<&str> = lines[start..end].to_vec();
            match pending.take() {
                Some((directive, at)) => {
                    steps.extend(step(chapter, &directive, at, start, &body));
                }
                None => assert!(
                    !(info.trim() == "sh"
                        && body.iter().any(|l| l.trim().starts_with("dreamcarve"))),
                    "{chapter}:{number}: a `sh` block of dreamcarve commands has no `{MARKER}` marker, so the test would not run it"
                ),
            }
            i = end + 1;
            continue;
        }
        if !line.is_empty() {
            assert!(
                pending.is_none(),
                "{chapter}:{number}: a `{MARKER}` marker must be followed by a fenced block"
            );
        }
        i += 1;
    }
    assert!(
        pending.is_none(),
        "{chapter}: marker at the end of the file"
    );
    steps
}

/// The steps one marked block makes. `at` is the marker's line and `first`
/// the 0-based index of the block's first line.
fn step(chapter: &str, directive: &str, at: usize, first: usize, body: &[&str]) -> Vec<Step> {
    let (verb, arg) = directive
        .split_once(' ')
        .map_or((directive, ""), |(v, a)| (v, a.trim()));
    let owned = || body.iter().map(|l| (*l).to_owned()).collect::<Vec<_>>();
    let file = || {
        assert!(!arg.is_empty(), "{chapter}:{at}: `{verb}` needs a file");
        arg.to_owned()
    };
    match verb.trim_end_matches(',') {
        "run" => {
            let exit = match arg {
                "" => 0,
                _ => arg
                    .strip_prefix("exit ")
                    .and_then(|n| n.trim().parse().ok())
                    .unwrap_or_else(|| panic!("{chapter}:{at}: expected `run, exit N`")),
            };
            body.iter()
                .enumerate()
                .filter(|(_, l)| !l.trim().is_empty() && !l.trim().starts_with('#'))
                .map(|(k, l)| {
                    let line = first + k + 1;
                    assert!(
                        !l.contains(['"', '\'', '$', '|', '>', '<', '&', ';', '`']),
                        "{chapter}:{line}: keep quick-start commands free of shell syntax: {l}"
                    );
                    let mut words = l.split_whitespace();
                    assert_eq!(
                        words.next(),
                        Some("dreamcarve"),
                        "{chapter}:{line}: only dreamcarve commands can be run: {l}"
                    );
                    Step::Run {
                        args: words.map(str::to_owned).collect(),
                        exit,
                        line,
                    }
                })
                .collect()
        }
        "edit" => {
            let changes = body
                .iter()
                .filter(|l| !l.trim().is_empty())
                .map(|l| {
                    let (key, value) = l
                        .trim()
                        .trim_end_matches(',')
                        .split_once(':')
                        .unwrap_or_else(|| {
                            panic!("{chapter}:{at}: not a `\"key\": value` line: {l}")
                        });
                    (key.trim().to_owned(), value.trim().to_owned())
                })
                .collect();
            vec![Step::Edit {
                file: file(),
                changes,
                line: at,
            }]
        }
        "write" => vec![Step::Write {
            file: file(),
            lines: owned(),
            line: at,
        }],
        "paste" => {
            let (file, key) = arg
                .split_once(' ')
                .unwrap_or_else(|| panic!("{chapter}:{at}: expected `paste FILE KEY`"));
            let key = format!("\"{}\":", key.trim());
            assert!(
                body.first().is_some_and(|l| l.starts_with(&key)),
                "{chapter}:{at}: a pasted block starts with {key}"
            );
            vec![Step::Paste {
                file: file.to_owned(),
                key,
                lines: owned(),
                line: at,
            }]
        }
        "excerpt" => vec![Step::Excerpt {
            file: file(),
            lines: owned(),
            line: at,
        }],
        "contains" => vec![Step::Contains {
            file: file(),
            lines: owned(),
            line: at,
        }],
        other => panic!("{chapter}:{at}: unknown doc-test step `{other}`"),
    }
}

/// Applies a hand edit: each key's line gets the new value, keeping its
/// indentation and any trailing comma. A key on several lines is the one
/// right after the block's previous key, where the chapter shows it.
fn edit(chapter: &str, path: &Path, changes: &[(String, String)], at: usize) {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{chapter}:{at}: cannot read {}: {e}", path.display()));
    let mut lines: Vec<String> = text.lines().map(str::to_owned).collect();
    let mut previous: Option<usize> = None;
    for (key, value) in changes {
        let mut found: Vec<usize> = lines
            .iter()
            .enumerate()
            .filter(|(_, l)| l.trim_start().starts_with(&format!("{key}:")))
            .map(|(i, _)| i)
            .collect();
        if found.len() > 1
            && let Some(next) = previous.map(|p| p + 1)
            && found.contains(&next)
        {
            found = vec![next];
        }
        let [index] = found[..] else {
            panic!(
                "{chapter}:{at}: the chapter says to change {key}, which is on {} lines of {}; a reader could not tell which",
                found.len(),
                path.display()
            );
        };
        let old = &lines[index];
        let indent = &old[..old.len() - old.trim_start().len()];
        let comma = if old.trim_end().ends_with(',') {
            ","
        } else {
            ""
        };
        lines[index] = format!("{indent}{key}: {value}{comma}");
        previous = Some(index);
    }
    std::fs::write(path, lines.join("\n") + "\n").expect("edited file written");
}

/// Pastes `new` over the block of `path` that opens with `key`: from the
/// one line that starts with it to the first later line, at the same
/// indentation, that closes it. The pasted lines take that indentation.
fn paste(chapter: &str, path: &Path, key: &str, new: &[String], at: usize) {
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("{chapter}:{at}: cannot read {}: {e}", path.display()));
    let mut lines: Vec<String> = text.lines().map(str::to_owned).collect();
    let found: Vec<usize> = lines
        .iter()
        .enumerate()
        .filter(|(_, l)| l.trim_start().starts_with(key))
        .map(|(i, _)| i)
        .collect();
    let [start] = found[..] else {
        panic!(
            "{chapter}:{at}: the chapter says to replace the {key} block, which opens on {} lines of {}; a reader could not tell which",
            found.len(),
            path.display()
        );
    };
    let indent = {
        let l = &lines[start];
        l[..l.len() - l.trim_start().len()].to_owned()
    };
    let end = (start + 1..lines.len())
        .find(|&i| {
            let l = &lines[i];
            l.len() > indent.len()
                && l.starts_with(&indent)
                && (l[indent.len()..].starts_with(']') || l[indent.len()..].starts_with('}'))
        })
        .unwrap_or_else(|| {
            panic!(
                "{chapter}:{at}: the {key} block of {} never closes",
                path.display()
            )
        });
    let pasted: Vec<String> = new
        .iter()
        .map(|l| {
            if l.is_empty() {
                String::new()
            } else {
                format!("{indent}{l}")
            }
        })
        .collect();
    lines.splice(start..=end, pasted);
    std::fs::write(path, lines.join("\n") + "\n").expect("pasted file written");
}

/// True when `shown` (from the chapter) stands for `actual` (from the
/// file): equal, or both the dated header line.
fn same_line(shown: &str, actual: &str) -> bool {
    shown == actual || (shown.contains(DATE_LINE) && actual.contains(DATE_LINE))
}

/// How a chapter is run.
struct Run<'a> {
    /// The chapter, relative to the repository root.
    chapter: &'a str,
    /// The drawing the chapter starts from: the fixture, relative to the
    /// repository root, and the name the chapter gives it.
    drawing: (&'a str, &'a str),
    /// Run with the drawing swapped for another of the same shapes: every
    /// command argument naming `drawing.1` names this instead, and the
    /// chapter's file excerpts, which show the first drawing's programs,
    /// are not compared.
    swap: Option<(&'a str, &'a str)>,
}

/// Runs every marked step of `run.chapter` in order, in an empty folder
/// holding the drawing, and returns the folder.
fn run_chapter(name: &str, run: &Run<'_>) -> PathBuf {
    let chapter = run.chapter;
    let path = repo_root().join(chapter);
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read the quick start {}: {e}", path.display()));
    let steps = steps(chapter, &text);
    assert!(
        steps.iter().any(|s| matches!(s, Step::Run { .. })),
        "{chapter} has no `run` step"
    );

    let dir = work_dir(name);
    let (fixture, drawing) = run.swap.unwrap_or(run.drawing);
    std::fs::copy(repo_root().join(fixture), dir.join(drawing)).expect("drawing copied");

    for step in &steps {
        match step {
            Step::Run { args, exit, line } => {
                let args: Vec<&str> = args
                    .iter()
                    .map(|a| match run.swap {
                        Some((_, swapped)) if a == run.drawing.1 => swapped,
                        _ => a.as_str(),
                    })
                    .collect();
                let out = Command::new(env!("CARGO_BIN_EXE_dreamcarve"))
                    .current_dir(&dir)
                    // The chapter runs with no user config, whatever the
                    // developer's own `config.toml` says.
                    .env("DREAMCARVE_CONFIG_DIR", dir.join("config"))
                    .args(&args)
                    .output()
                    .expect("binary runs");
                assert_eq!(
                    out.status.code(),
                    Some(*exit),
                    "{chapter}:{line}: `dreamcarve {}` exit code\nstdout:\n{}\nstderr:\n{}",
                    args.join(" "),
                    String::from_utf8_lossy(&out.stdout),
                    String::from_utf8_lossy(&out.stderr)
                );
                if *exit != 0 {
                    let programs: Vec<_> = std::fs::read_dir(&dir)
                        .expect("work dir readable")
                        .filter_map(Result::ok)
                        .filter(|e| e.path().extension().is_some_and(|x| x == "nc"))
                        .map(|e| e.path())
                        .collect();
                    assert!(
                        programs.is_empty(),
                        "{chapter}:{line}: `dreamcarve {}` failed but a program exists: {programs:?}",
                        args.join(" ")
                    );
                }
            }
            Step::Edit {
                file,
                changes,
                line,
            } => edit(chapter, &dir.join(file), changes, *line),
            Step::Write { file, lines, line } => {
                let target = dir.join(file);
                assert!(
                    !target.exists(),
                    "{chapter}:{line}: the chapter makes {file}, which already exists"
                );
                std::fs::write(target, lines.join("\n") + "\n").expect("file written");
            }
            Step::Paste {
                file,
                key,
                lines,
                line,
            } => paste(chapter, &dir.join(file), key, lines, *line),
            Step::Excerpt { file, lines, line } if run.swap.is_none() => {
                let actual = std::fs::read_to_string(dir.join(file))
                    .unwrap_or_else(|e| panic!("{chapter}:{line}: cannot read {file}: {e}"));
                let actual: Vec<&str> = actual.lines().collect();
                assert!(
                    lines.len() <= actual.len(),
                    "{chapter}:{line}: excerpt is longer than {file}"
                );
                for (k, (shown, real)) in lines.iter().zip(&actual).enumerate() {
                    assert!(
                        same_line(shown, real),
                        "{chapter}:{line}: excerpt line {} is `{shown}`, but {file} has `{real}`",
                        k + 1
                    );
                }
            }
            Step::Contains { file, lines, line } if run.swap.is_none() => {
                let actual = std::fs::read_to_string(dir.join(file))
                    .unwrap_or_else(|e| panic!("{chapter}:{line}: cannot read {file}: {e}"));
                let actual: Vec<&str> = actual.lines().collect();
                assert!(
                    !lines.is_empty()
                        && actual
                            .windows(lines.len())
                            .any(|w| w.iter().zip(lines).all(|(a, s)| same_line(s, a))),
                    "{chapter}:{line}: {file} does not have these lines one after the other:\n{}",
                    lines.join("\n")
                );
            }
            Step::Excerpt { .. } | Step::Contains { .. } => {}
        }
    }
    dir
}

/// Every marked step of the phase 1 quick start, run in order in an empty
/// folder holding `coaster.svg`, does what the chapter says: each command
/// exits with the code the chapter expects, a failed command writes no
/// program, the hand edit applies to exactly the lines it names, and the
/// program excerpt the chapter shows is the start of the written program.
#[test]
fn quick_start_runs_as_written() {
    let text = std::fs::read_to_string(repo_root().join(FIRST_CUT)).expect("chapter readable");
    assert!(
        steps(FIRST_CUT, &text)
            .iter()
            .any(|s| matches!(s, Step::Edit { .. })),
        "{FIRST_CUT} has no `edit` step: the feeds must be set before export"
    );
    run_chapter(
        "quick_start_runs_as_written",
        &Run {
            chapter: FIRST_CUT,
            drawing: ("fixtures/coaster.svg", "coaster.svg"),
            swap: None,
        },
    );
}

/// The tool-centre limits and rates one program must keep to.
struct Limits {
    /// Safe Z, mm above the stock top.
    safe_z_mm: f64,
    /// The deepest any move may go: the stock thickness plus the
    /// through-cut allowance, below the stock top.
    floor_mm: f64,
    /// The stock, `(width, height)`, mm, from work zero.
    stock_mm: (f64, f64),
    /// The tool's radius, feed and plunge rate.
    radius_mm: f64,
    feed_mm_min: f64,
    plunge_mm_min: f64,
    /// The spindle line the program must start the spindle with.
    spindle: &'static str,
}

/// The XY length of `m`, mm: the chord, or the arc for `G2`/`G3`.
fn xy_length(m: &MachineMove) -> f64 {
    let (fx, fy) = (m.from.x.unwrap_or(0.0), m.from.y.unwrap_or(0.0));
    let (tx, ty) = (m.to.x.unwrap_or(fx), m.to.y.unwrap_or(fy));
    let chord = (tx - fx).hypot(ty - fy);
    let (Some(i), Some(j)) = (m.arc.i, m.arc.j) else {
        return chord;
    };
    if !matches!(m.kind, MotionKind::ArcCw | MotionKind::ArcCcw) {
        return chord;
    }
    let (cx, cy) = (fx + i, fy + j);
    let r = i.hypot(j);
    let a0 = (fy - cy).atan2(fx - cx);
    let a1 = (ty - cy).atan2(tx - cx);
    let tau = std::f64::consts::TAU;
    let sweep = if m.kind == MotionKind::ArcCcw {
        (a1 - a0).rem_euclid(tau)
    } else {
        (a0 - a1).rem_euclid(tau)
    };
    let sweep = if sweep < 1e-9 { tau } else { sweep };
    r * sweep
}

/// The safety rules a user can check on the written program alone, here
/// checked independently of the emitter's own safety pass (which `export`
/// has already passed, or it would have written nothing): S1 no move below
/// the stock bottom less the allowance; S2 every rapid in XY at safe Z;
/// S2 and S15 every rapid down ends above the stock top or no deeper than
/// a cut has reached at that point (one that ended there, or a straight
/// cut through it: a Pocket's later pass starts its ramp just above the
/// floor a link cut, #214); S3 and S10 every cut has a feed no faster
/// than the tool's, and goes down no faster than its plunge rate; S4 the
/// spindle starts before the first cut and the program ends `M5`, `M30`;
/// and the tool's edge stays on the stock.
fn assert_program_safe(name: &str, program: &str, limits: &Limits) {
    let moves = dc_gcode::parse_motion(program)
        .unwrap_or_else(|e| panic!("{name} parses as the controller reads it: {e}"));
    assert!(!moves.is_empty(), "{name} moves");
    let tol = 1e-6;
    let mut cut_depth: Vec<((f64, f64), f64)> = Vec::new();
    // Straight cuts: from XY and Z, to XY and Z.
    let mut straight: Vec<(Xyz, Xyz)> = Vec::new();
    let first_cut = moves
        .iter()
        .find(|m| m.kind.is_cut())
        .expect("the program cuts")
        .line;
    let spindle_line = program
        .lines()
        .position(|l| l.trim() == limits.spindle)
        .unwrap_or_else(|| panic!("{name} starts the spindle with `{}`", limits.spindle))
        + 1;
    assert!(
        spindle_line < first_cut,
        "{name}: the spindle starts (line {spindle_line}) before the first cut (line {first_cut})"
    );
    let tail: Vec<&str> = program.lines().rev().take(2).collect();
    assert_eq!(tail, ["M30", "M5"], "{name} ends with M5, M30");

    let (width, height) = limits.stock_mm;
    for m in &moves {
        let (Some(x), Some(y), Some(z)) = (m.to.x, m.to.y, m.to.z) else {
            // Before the first full position: only the opening Z rapid.
            assert_eq!(m.kind, MotionKind::Rapid, "{name}:{} first move", m.line);
            assert!(
                m.to.z.is_some_and(|z| (z - limits.safe_z_mm).abs() < tol),
                "{name}:{}: the first move rises to safe Z",
                m.line
            );
            continue;
        };
        let from_z = m.from.z.unwrap_or(limits.safe_z_mm);
        assert!(
            z >= -limits.floor_mm - tol,
            "{name}:{}: Z {z} is below the stock bottom less the allowance (S1)",
            m.line
        );
        let r = limits.radius_mm;
        assert!(
            x - r >= -tol && x + r <= width + tol && y - r >= -tol && y + r <= height + tol,
            "{name}:{}: the tool's edge leaves the stock at X {x} Y {y}",
            m.line
        );
        let moves_xy = m
            .from
            .x
            .zip(m.from.y)
            .is_some_and(|(fx, fy)| (fx - x).abs() > tol || (fy - y).abs() > tol);
        if m.kind == MotionKind::Rapid {
            if moves_xy {
                assert!(
                    (from_z - limits.safe_z_mm).abs() < tol && (z - limits.safe_z_mm).abs() < tol,
                    "{name}:{}: a rapid in XY below safe Z (S2)",
                    m.line
                );
            }
            if z < from_z - tol && z < -tol {
                let through = straight.iter().filter_map(|&((ax, ay, az), (bx, by, bz))| {
                    let (dx, dy) = (bx - ax, by - ay);
                    let length_sq = dx * dx + dy * dy;
                    let t = if length_sq > 0.0 {
                        (((x - ax) * dx + (y - ay) * dy) / length_sq).clamp(0.0, 1.0)
                    } else {
                        0.0
                    };
                    let (px, py) = (ax + dx * t, ay + dy * t);
                    ((px - x).hypot(py - y) < 2e-3).then_some(az + (bz - az) * t)
                });
                let reached = cut_depth
                    .iter()
                    .filter(|((cx, cy), _)| (cx - x).abs() < 1e-3 && (cy - y).abs() < 1e-3)
                    .map(|(_, d)| *d)
                    .chain(through)
                    .fold(f64::INFINITY, f64::min);
                assert!(
                    z >= reached - tol,
                    "{name}:{}: a rapid down to Z {z} into material not cut yet (S15)",
                    m.line
                );
            }
            continue;
        }
        let feed = m
            .feed
            .unwrap_or_else(|| panic!("{name}:{}: a cut with no feed (S3)", m.line));
        assert!(
            feed > 0.0 && feed <= limits.feed_mm_min + tol,
            "{name}:{}: feed {feed} is not in (0, {}] (S3)",
            m.line,
            limits.feed_mm_min
        );
        let dz = from_z - z;
        if dz > tol {
            let length = xy_length(m).hypot(dz);
            let down = feed * dz / length;
            assert!(
                down <= limits.plunge_mm_min + 1e-3,
                "{name}:{}: goes down at {down} mm/min, faster than the plunge rate {} (S10)",
                m.line,
                limits.plunge_mm_min
            );
        }
        cut_depth.push(((x, y), z));
        if m.kind == MotionKind::Linear
            && let (Some(fx), Some(fy)) = (m.from.x, m.from.y)
        {
            straight.push(((fx, fy, from_z), (x, y, z)));
        }
    }
}

/// A point as written: X, Y and Z.
type Xyz = (f64, f64, f64);

/// The pieces of `line`: each number, and each run of other text.
fn tokens(line: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut start = 0;
    let mut in_number = false;
    for (i, c) in line.char_indices() {
        let number_char = c.is_ascii_digit() || matches!(c, '.' | 'e' | 'E' | '-' | '+');
        let starts_number = c.is_ascii_digit() || c == '-';
        let now = if in_number {
            number_char
        } else {
            starts_number
        };
        if now != in_number && i > start {
            out.push(&line[start..i]);
            start = i;
        }
        in_number = now;
    }
    if start < line.len() {
        out.push(&line[start..]);
    }
    out
}

/// `built`, the project the chapter's steps wrote in `dir`, is the
/// committed `fixture`: the same lines, with every number equal to within
/// 1e-6. Imported coordinates differ in their last bits between platforms'
/// maths libraries (a DXF spline, an SVG arc), so the text cannot be
/// compared byte for byte.
fn assert_same_project(built: &str, committed: &str, fixture: &str, dir: &Path) {
    let (a, b): (Vec<&str>, Vec<&str>) = (built.lines().collect(), committed.lines().collect());
    let hint = format!(
        "if the chapter changed on purpose, copy {} over {fixture}",
        dir.join("plaque.dcv").display()
    );
    assert_eq!(
        a.len(),
        b.len(),
        "the project has a different number of lines from {fixture}; {hint}"
    );
    for (k, (x, y)) in a.iter().zip(&b).enumerate() {
        if x == y {
            continue;
        }
        let (tx, ty) = (tokens(x), tokens(y));
        let same = tx.len() == ty.len()
            && tx.iter().zip(&ty).all(|(p, q)| {
                p == q
                    || matches!((p.parse::<f64>(), q.parse::<f64>()), (Ok(u), Ok(v)) if (u - v).abs() <= 1e-6)
            });
        assert!(
            same,
            "line {} of the project is `{x}`, but {fixture} has `{y}`; {hint}",
            k + 1
        );
    }
}

/// The phase 2 quick start (`docs/book/src/quick-start/plaque.md`, issue
/// #125) run as written on `tests/fixtures/plaque.dxf`: every command exits
/// as the chapter says, the hand edits and pasted blocks apply, every
/// excerpt is in the program it names, and the finished project is the
/// committed `tests/fixtures/plaque.dcv`. Acceptance test 18: export
/// writes `plaque-1-T2.nc` (the Bore and the Engrave, with the 3.175 mm
/// end mill) and `plaque-2-T1.nc` (both Pockets and the Profile, with the
/// 6.35 mm end mill), lists them in that order, and each passes the
/// safety rules on its own (maintainer decision 2026-10-24: the holes
/// were a Drill with the 6.35 mm bit, and the Engrave came last).
///
/// The same chapter run on `plaque.svg` instead builds the committed
/// `tests/fixtures/plaque-svg.dcv`, which
/// `cli::plaque_dxf_exports_same_programs_as_svg` compares.
#[test]
fn pocketed_plaque_from_dxf_chapter_runs() {
    let run = Run {
        chapter: PLAQUE,
        drawing: ("tests/fixtures/plaque.dxf", "plaque.dxf"),
        swap: None,
    };
    let text = std::fs::read_to_string(repo_root().join(PLAQUE)).expect("chapter readable");
    let steps = steps(PLAQUE, &text);
    for (what, has) in [
        (
            "write",
            steps.iter().any(|s| matches!(s, Step::Write { .. })),
        ),
        (
            "paste",
            steps.iter().any(|s| matches!(s, Step::Paste { .. })),
        ),
        (
            "excerpt",
            steps.iter().any(|s| matches!(s, Step::Excerpt { .. })),
        ),
    ] {
        assert!(has, "{PLAQUE} has no `{what}` step");
    }
    let dir = run_chapter("pocketed_plaque_from_dxf_chapter_runs", &run);

    let built = std::fs::read_to_string(dir.join("plaque.dcv")).expect("plaque.dcv written");
    let committed = std::fs::read_to_string(repo_root().join("tests/fixtures/plaque.dcv"))
        .expect("tests/fixtures/plaque.dcv readable");
    assert_same_project(&built, &committed, "tests/fixtures/plaque.dcv", &dir);

    let mut programs: Vec<String> = std::fs::read_dir(&dir)
        .expect("work dir readable")
        .filter_map(Result::ok)
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".nc"))
        .collect();
    programs.sort();
    assert_eq!(programs, ["plaque-1-T2.nc", "plaque-2-T1.nc"]);

    let out = Command::new(env!("CARGO_BIN_EXE_dreamcarve"))
        .current_dir(&dir)
        .env("DREAMCARVE_CONFIG_DIR", dir.join("config"))
        .args(["export", "plaque.dcv"])
        .output()
        .expect("binary runs");
    let stdout = String::from_utf8_lossy(&out.stdout);
    let first = stdout
        .find("1. plaque-1-T2.nc")
        .expect("program 1 listed first");
    let second = stdout
        .find("2. plaque-2-T1.nc")
        .expect("program 2 listed second");
    assert!(first < second, "{stdout}");

    let read = |name: &str| std::fs::read_to_string(dir.join(name)).expect("program readable");
    let (one, two) = (read("plaque-1-T2.nc"), read("plaque-2-T1.nc"));
    let operations = |program: &str| -> Vec<String> {
        program
            .lines()
            .filter(|l| l.starts_with("( Operation "))
            .map(str::to_owned)
            .collect()
    };
    assert_eq!(
        operations(&one),
        [
            "( Operation 1: Screw holes )",
            "( Operation 2: Border and squiggle )",
        ]
    );
    assert_eq!(
        operations(&two),
        [
            "( Operation 1: Panel )",
            "( Operation 2: Square recess )",
            "( Operation 3: Cut out )",
        ]
    );

    let stock = |plunge_mm_min, feed_mm_min, radius_mm| Limits {
        safe_z_mm: 15.0,
        floor_mm: 11.8 + 0.2,
        stock_mm: (170.0, 120.0),
        radius_mm,
        feed_mm_min,
        plunge_mm_min,
        spindle: "M3 S18000",
    };
    assert_program_safe("plaque-1-T2.nc", &one, &stock(300.0, 1000.0, 1.5875));
    assert_program_safe("plaque-2-T1.nc", &two, &stock(500.0, 1500.0, 3.175));
}

