//! The single-byte Windows ("ANSI") code pages a DXF file before R2007 may
//! be written in, as `$DWGCODEPAGE` names them (`ANSI_874`, `ANSI_1250` …
//! `ANSI_1258`; DXF Reference, "HEADER Section Group Codes") (#209).
//!
//! Each table is the upper half (bytes 0x80–0xFF) of Microsoft's mapping
//! for the code page, as Microsoft published it through the Unicode
//! Consortium (`MAPPINGS/VENDORS/MICSFT/WINDOWS/CP874.TXT`, `CP1250.TXT` …
//! `CP1258.TXT`); bytes below 0x80 are ASCII in every one. A byte the
//! mapping leaves undefined reads as the C1 control of the same value when
//! it is in 0x80–0x9F, as Windows-1252's always has here, and as U+FFFD
//! above that.
//!
//! The multi-byte East Asian code pages (`ANSI_932` Shift-JIS, `ANSI_936`,
//! `ANSI_949`, `ANSI_950`) and the DOS ones have no table: text in them is
//! read as Windows-1252 with a warning.

/// A single-byte Windows code page.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct CodePage {
    /// The Windows code page number: 1251 for `ANSI_1251`.
    number: u16,
    /// The characters of bytes 0x80–0xFF.
    high: &'static [char; 128],
}

impl CodePage {
    /// Windows-1252 (Western European), what DXF files before R2007 are
    /// read in when `$DWGCODEPAGE` is absent.
    pub(super) const WINDOWS_1252: Self = Self {
        number: 1252,
        high: &CP1252,
    };

    /// The code page a `$DWGCODEPAGE` value names, in any case; `None` for
    /// a code page without a table here.
    pub(super) fn from_dwgcodepage(name: &str) -> Option<Self> {
        let name = name.trim();
        let prefix = name.get(..5)?;
        if !prefix.eq_ignore_ascii_case("ANSI_") {
            return None;
        }
        let number: u16 = name.get(5..)?.parse().ok()?;
        PAGES.iter().find(|page| page.number == number).copied()
    }

    /// One byte of text in this code page as a character.
    pub(super) fn char(self, byte: u8) -> char {
        match byte.checked_sub(0x80) {
            None => char::from(byte),
            Some(i) => self
                .high
                .get(usize::from(i))
                .copied()
                .unwrap_or(char::REPLACEMENT_CHARACTER),
        }
    }
}

