//! Generates `StrKey` from `strings/en.toml` (`docs/specs/phase-4/design.md`,
//! "Strings"): one variant per key, `command.label.set_stock` becoming
//! `CommandLabelSetStock`, with the key and its English text as `const fn`s.
//! A key that is not in the table fails to compile; a value that is not a
//! string, or a key with a character outside `[a-z0-9_.]`, fails the build.

use std::error::Error;
use std::fmt::Write as _;
use std::path::Path;

/// One entry of the table: its dotted key and English text.
struct Entry {
    key: String,
    text: String,
}

/// `command.label.set_stock` → `CommandLabelSetStock`.
fn variant_name(key: &str) -> String {
    key.split(['.', '_'])
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect::<String>(),
                None => String::new(),
            }
        })
        .collect()
}

/// Flattens nested tables into dotted keys, in table order.
fn flatten(table: &toml::Table, prefix: &str, out: &mut Vec<Entry>) -> Result<(), String> {
    for (name, value) in table {
        if name.is_empty()
            || !name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        {
            return Err(format!(
                "strings/en.toml: key `{prefix}{name}` is not lower_snake_case"
            ));
        }
        let key = if prefix.is_empty() {
            name.clone()
        } else {
            format!("{prefix}.{name}")
        };
        match value {
            toml::Value::Table(inner) => flatten(inner, &key, out)?,
            toml::Value::String(text) => out.push(Entry {
                key,
                text: text.clone(),
            }),
            other => {
                return Err(format!(
                    "strings/en.toml: `{key}` is {}, not a string",
                    other.type_str()
                ));
            }
        }
    }
    Ok(())
}

/// The Rust source of `StrKey` and its tables.
fn generate(entries: &[Entry]) -> Result<String, Box<dyn Error>> {
    let mut out = String::new();
    writeln!(
        out,
        "/// A key of the string table, one variant per entry of `strings/en.toml`\n\
         /// (generated by `build.rs`; `docs/specs/phase-4/design.md`, \"Strings\").\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]\n\
         pub enum StrKey {{"
    )?;
    for entry in entries {
        writeln!(
            out,
            "    /// `{}`: {:?}\n    {},",
            entry.key,
            entry.text,
            variant_name(&entry.key)
        )?;
    }
    writeln!(out, "}}\n\nimpl StrKey {{")?;
    writeln!(out, "    /// Every key, in the table's order.")?;
    writeln!(out, "    pub const ALL: &'static [StrKey] = &[")?;
    for entry in entries {
        writeln!(out, "        StrKey::{},", variant_name(&entry.key))?;
    }
    writeln!(out, "    ];\n")?;
    writeln!(
        out,
        "    /// The dotted key in `strings/en.toml`.\n    #[must_use]\n    \
         pub const fn key(self) -> &'static str {{\n        match self {{"
    )?;
    for entry in entries {
        writeln!(
            out,
            "            Self::{} => {:?},",
            variant_name(&entry.key),
            entry.key
        )?;
    }
    writeln!(out, "        }}\n    }}\n")?;
    writeln!(
        out,
        "    /// The English text, the table shipped in the binary.\n    #[must_use]\n    \
         pub const fn english(self) -> &'static str {{\n        match self {{"
    )?;
    for entry in entries {
        writeln!(
            out,
            "            Self::{} => {:?},",
            variant_name(&entry.key),
            entry.text
        )?;
    }
    writeln!(out, "        }}\n    }}\n}}")?;
    Ok(out)
}

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=strings/en.toml");
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let table_path = Path::new(&manifest_dir).join("strings/en.toml");
    let text = std::fs::read_to_string(&table_path)?;
    let table: toml::Table = text.parse()?;
    let mut entries = Vec::new();
    flatten(&table, "", &mut entries)?;
    if entries.is_empty() {
        return Err("strings/en.toml has no entries".into());
    }
    let mut names: Vec<String> = entries.iter().map(|e| variant_name(&e.key)).collect();
    names.sort_unstable();
    if let Some(pair) = names.windows(2).find(|w| w.first() == w.get(1)) {
        return Err(format!(
            "strings/en.toml: two keys share the variant name {:?}",
            pair.first().map_or("", String::as_str)
        )
        .into());
    }
    let out_dir = std::env::var("OUT_DIR")?;
    std::fs::write(Path::new(&out_dir).join("str_key.rs"), generate(&entries)?)?;
    Ok(())
}
