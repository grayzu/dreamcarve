//! Tests for the license header checker (`docs/specs/phase-0/design.md`,
//! "Test plan").

// Test helpers may panic on setup failure (docs/rust-guidelines.md, "Toolchain").
#![allow(clippy::expect_used)]

use std::fs;
use std::path::{Path, PathBuf};

use check_headers::{check_source, find_sources};

const DREAMCARVE: &str = "\
// Copyright 2026 The DreamCarve Contributors
// SPDX-License-Identifier: Apache-2.0

fn main() {}
";

const UPSTREAM: &str = "\
// Copyright 2026 Franja (Frank) Povazanj (PureCutCNC)
// Copyright 2026 The DreamCarve Contributors
// SPDX-License-Identifier: Apache-2.0
//
// Ported to Rust and modified from PureCutCNC:
//   src/engine/toolpaths/geometry.ts

pub fn offset() {}
";

const NONE: &str = "\
//! A module that forgot its header.

pub fn offset() {}
";

#[test]
fn accepts_dreamcarve_header() {
    assert_eq!(
        check_source(Path::new("crates/dc-cam/src/lib.rs"), DREAMCARVE),
        Ok(())
    );
}

#[test]
fn accepts_upstream_header() {
    assert_eq!(
        check_source(Path::new("crates/dc-geometry/src/offset.rs"), UPSTREAM),
        Ok(())
    );
}

#[test]
fn rejects_missing_header() {
    let err = check_source(Path::new("crates/dc-geometry/src/offset.rs"), NONE)
        .expect_err("a file without a header must be rejected");
    let message = err.to_string();
    assert!(
        message.contains("crates/dc-geometry/src/offset.rs"),
        "message must name the file, was: {message}"
    );
}

#[test]
fn skips_generated_and_target() {
    let root = scratch_dir("skips_generated_and_target");
    write(&root.join("target/debug/build/out.rs"), NONE);
    write(
        &root.join("crates/dc-cam/src/gen.rs"),
        "// @generated by build.rs\nfn x() {}\n",
    );
    write(&root.join("crates/dc-cam/src/lib.rs"), DREAMCARVE);
    write(&root.join("crates/dc-cam/README.md"), "not rust");

    let mut found = find_sources(&root).expect("walk succeeds");
    found.sort();

    assert_eq!(found, vec![root.join("crates/dc-cam/src/lib.rs")]);
    fs::remove_dir_all(&root).expect("cleanup");
}

fn scratch_dir(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("check-headers-{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("create scratch dir");
    dir
}

fn write(path: &Path, contents: &str) {
    fs::create_dir_all(path.parent().expect("has parent")).expect("mkdir");
    fs::write(path, contents).expect("write");
}
