/**
 * Capture a golden case from a local PureCutCNC checkout.
 *
 *   npx tsx capture.ts --purecutcnc ../purecutcnc --case smoke
 *
 * Loads `cases/<name>.camj`, runs PureCutCNC's own `computeOperationToolpath`
 * and `runPostProcessor` on every enabled operation with the grblHAL builtin
 * machine definition, and writes `tests/golden/<name>/program.nc`,
 * `toolpath.json` (key-sorted, see PureCutCNC's `parityRecord.canonicalize`),
 * and a README naming the PureCutCNC commit. `cargo test` reads the written
 * files; Node is needed only to run this script.
 *
 * Dev-only tool, not part of the Cargo workspace (docs/specs/phase-0/design.md,
 * "Parity tool").
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..', '..')

function arg(name: string, fallback?: string): string {
  const i = process.argv.indexOf(`--${name}`)
  if (i !== -1 && process.argv[i + 1]) return process.argv[i + 1]
  if (fallback !== undefined) return fallback
  console.error(`capture: missing --${name}`)
  process.exit(2)
}

const checkout = resolve(arg('purecutcnc', join(repoRoot, '..', 'purecutcnc')))
const caseName = arg('case')
const postId = arg('post', 'grblhal')
const FROZEN_DATE = '2026-01-01'

async function load<T>(relativePath: string): Promise<T> {
  return (await import(pathToFileURL(join(checkout, relativePath)).href)) as T
}

type Json = Record<string, unknown>

interface Engine {
  computeOperationToolpath: (project: Json, operation: Json) => { result: Json } | null
  runPostProcessor: (input: Json) => { gcode: string }
  normalizeProject: (input: Json) => Json
  normalizeToolForProject: (tool: Json, project: Json) => Json
  validateMachineDefinition: (data: unknown) => Json
  canonicalize: (value: unknown) => string
}

async function engine(): Promise<Engine> {
  const [gen, post, format, geometry, types, record] = await Promise.all([
    load<Pick<Engine, 'computeOperationToolpath'>>('src/engine/toolpaths/generateOperation.ts'),
    load<Pick<Engine, 'runPostProcessor'>>('src/engine/gcode/postprocessor.ts'),
    load<Pick<Engine, 'normalizeProject'>>('src/store/helpers/projectFormat.ts'),
    load<Pick<Engine, 'normalizeToolForProject'>>('src/engine/toolpaths/geometry.ts'),
    load<Pick<Engine, 'validateMachineDefinition'>>('src/engine/gcode/types.ts'),
    load<Pick<Engine, 'canonicalize'>>('src/engine/toolpaths/parityRecord.ts'),
  ])
  return { ...gen, ...post, ...format, ...geometry, ...types, ...record }
}

function upstreamCommit(): string {
  return execFileSync('git', ['-C', checkout, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
}

async function main(): Promise<void> {
  const e = await engine()
  const casePath = join(here, 'cases', `${caseName}.camj`)
  const project = e.normalizeProject(JSON.parse(readFileSync(casePath, 'utf8')) as Json)
  const definition = e.validateMachineDefinition(
    JSON.parse(readFileSync(join(checkout, 'src/engine/gcode/definitions', `${postId}.json`), 'utf8')),
  )

  const operations = (project.operations as Json[]).filter((op) => op.enabled !== false)
  const tools = project.tools as Json[]
  const emitted = operations.map((operation) => {
    const envelope = e.computeOperationToolpath(project, operation)
    if (!envelope) throw new Error(`capture: PureCutCNC does not generate operation kind ${String(operation.kind)}`)
    const tool = tools.find((t) => t.id === operation.toolRef)
    if (!tool) throw new Error(`capture: operation ${String(operation.id)} references missing tool ${String(operation.toolRef)}`)
    return { operation, tool: e.normalizeToolForProject(tool, project), toolpath: envelope.result }
  })

  const posted = e.runPostProcessor({
    project,
    definition,
    operations: emitted,
    options: { emitToolChanges: true, emitCoolant: false, programName: caseName },
  })
  // The `{date}` header token is the only wall-clock input; freeze it so a
  // re-capture on another day is byte-identical.
  const gcode = posted.gcode.replace(/Generated by PureCutCNC on \d{4}-\d{2}-\d{2}/, `Generated by PureCutCNC on ${FROZEN_DATE}`)

  const outDir = join(repoRoot, 'tests', 'golden', caseName)
  mkdirSync(outDir, { recursive: true })
  writeFileSync(join(outDir, 'program.nc'), gcode.endsWith('\n') ? gcode : `${gcode}\n`)
  writeFileSync(
    join(outDir, 'toolpath.json'),
    `${e.canonicalize(emitted.map(({ operation, toolpath }) => ({ operationId: operation.id, toolpath })))}\n`,
  )

  const meta = project.meta as Json
  const readme = [
    `# Golden case: ${caseName}`,
    '',
    `Captured from PureCutCNC commit \`${upstreamCommit()}\` with`,
    `\`tools/parity/capture.ts --case ${caseName} --post ${postId}\`.`,
    '',
    `- Source: \`tools/parity/cases/${caseName}.camj\` (PureCutCNC project format v${String(project.version)}, units ${String(meta.units)})`,
    `- Post-processor: PureCutCNC builtin \`${postId}\``,
    `- Operations: ${operations.map((op) => `\`${String(op.id)}\` (${String(op.kind)})`).join(', ')}`,
    `- Header date frozen to ${FROZEN_DATE} by the capture script.`,
    '- Tolerance: coordinates compare to 0.001 mm after DreamCarve maps its Y-up',
    '  frame to the machine frame; PureCutCNC G-code is already machine-frame.',
    '',
    'Files: `program.nc` is the emitted G-code; `toolpath.json` is the',
    'key-sorted toolpath per operation in PureCutCNC\'s internal (Y-down) frame.',
    '',
  ].join('\n')
  writeFileSync(join(outDir, 'README.md'), readme)
  console.log(`capture: wrote ${outDir} (${emitted.length} operation(s), ${gcode.split('\n').length} lines of G-code)`)
}

main().catch((err: unknown) => {
  console.error(err)
  process.exit(1)
})
